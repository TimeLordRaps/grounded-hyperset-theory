@pytest.mark.parametrize("k, factorial", [(2, 2), (3, 6), (4, 24), (5, 120), (6, 720)])
def test_a_star_has_k_factorial_pointed_automorphisms(k: int, factorial: int) -> None:
    # The root is fixed and the leaves are interchangeable, so Aut is S_k.
    assert len(automorphism_group(star(k), pointed=True)) == factorial


@pytest.mark.parametrize("n", [3, 4, 5, 7])
def test_a_pointed_directed_cycle_has_only_the_identity(n: int) -> None:
    # Fixing the root fixes its successor, and so on around the cycle.
    assert len(automorphism_group(directed_cycle(n), pointed=True)) == 1


def test_every_returned_automorphism_fixes_the_root_and_preserves_edges() -> None:
    apg = star(4)
    root = Node(0)
    for auto in automorphism_group(apg, pointed=True):
        assert auto.apply(root) == root
        for u in apg.nodes:
            assert {auto.apply(v) for v in apg.children(u)} == apg.children(auto.apply(u))


def test_the_automorphisms_form_a_group_closed_under_composition() -> None:
    group = find_apg_automorphisms(star(4), pointed=True)
    elements = group.elements()
    assert all(a * b in group for a in elements for b in elements)
    assert all(~a in group for a in elements)


def test_the_automorphism_search_returns_every_element_as_a_generator() -> None:
    # Not a defect -- a group generates itself -- but worth pinning, because it
    # is why every existing test of `orbit` took the full-group path and the
    # generating-set path stayed unexercised until it broke.
    for k in (3, 4, 5):
        group = find_apg_automorphisms(star(k), pointed=True)
        assert set(group.generators) == set(group.elements())
        assert len(group.generators) == math.factorial(k)


def test_a_group_of_prime_order_is_abelian_and_a_symmetric_one_is_not() -> None:
    assert PermutationGroup([rotation(5)]).is_abelian() is True
    nodes = [Node(i) for i in range(5)]
    swap = Permutation({nodes[0]: nodes[1], nodes[1]: nodes[0],
                        nodes[2]: nodes[2], nodes[3]: nodes[3], nodes[4]: nodes[4]})
    assert PermutationGroup([rotation(5), swap]).is_abelian() is False
