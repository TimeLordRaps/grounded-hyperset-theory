def test_the_quotient_is_the_same_from_generators_or_from_the_group() -> None:
    apg = star(4)
    group = find_apg_automorphisms(apg, pointed=True)
    from_generators = quotient_by_symmetry(apg, group.generators)
    from_elements = quotient_by_symmetry(apg, group.elements())
    assert len(from_generators.nodes) == len(from_elements.nodes)
    assert from_generators.edge_count == from_elements.edge_count


def test_quotienting_the_star_gives_a_root_and_one_leaf_block() -> None:
    apg = star(4)
    group = find_apg_automorphisms(apg, pointed=True)
    quotient = quotient_by_symmetry(apg, group.elements())
    assert len(quotient.nodes) == 2


def test_a_generating_set_no_longer_crashes_the_quotient() -> None:
    # This raised KeyError out of an internal dict.
    apg = AccessiblePointedGraph(root=0, edges={0: [1, 2, 3, 4], **{i: [] for i in range(1, 5)}})
    quotient = quotient_by_symmetry(apg, PermutationGroup([rotation(5)]).generators)
    assert len(quotient.nodes) == 1


def test_the_trivial_group_leaves_the_graph_alone() -> None:
    apg = directed_cycle(4)
    group = find_apg_automorphisms(apg, pointed=True)
    quotient = quotient_by_symmetry(apg, group.elements())
    assert len(quotient.nodes) == len(apg.nodes)


# ============================================================================
# 4. Group-theoretic invariants, which need no reference implementation
# ============================================================================


@pytest.mark.parametrize("k", [2, 3, 4, 5])
def test_orbit_stabilizer_holds_for_every_node(k: int) -> None:
    # |G| = |orbit(x)| * |stabilizer(x)|. Breaks if the closure, the orbit or the
    # stabilizer is wrong, without the answer being known in advance.
    group = find_apg_automorphisms(star(k), pointed=True)
    for node in group.domain:
        assert len(orbit(node, group.elements())) * group.stabilizer(node).order == group.order


@pytest.mark.parametrize("k", [2, 3, 4, 5])
def test_orbit_stabilizer_holds_through_a_real_generating_set(k: int) -> None:
    # Two generators, k! elements. This is the route that was broken: the orbit
    # of a leaf came back as the one or two leaves a single generator moved it
    # to, so |orbit| * |stab| undershot |G| by the whole factor it was missing.
    group = symmetric_on_leaves(k)
    assert group.order == math.factorial(k)
    assert len(group.generators) <= 2
    for node in group.domain:
        assert len(orbit(node, group.generators)) * group.stabilizer(node).order == group.order


@pytest.mark.parametrize("k", [2, 3, 4, 5])
def test_lagrange_the_stabilizer_order_divides_the_group_order(k: int) -> None:
    group = find_apg_automorphisms(star(k), pointed=True)
    for node in group.domain:
        assert group.order % group.stabilizer(node).order == 0


