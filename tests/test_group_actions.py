"""Orbits must be orbits, whether the caller hands over a group or generators.

`orbit(node, group)` applied each supplied permutation once. That is the orbit
when `group` is every element of the group and the one-step image set otherwise,
and `PermutationGroup.generators` is a public attribute holding exactly the
otherwise. Under the cyclic group generated by `(0 1 2 3 4)` the orbit of node 0
is all five nodes and it returned `{1}`; `all_orbits` then left nodes in no block
at all despite being documented as a partition, and `quotient_by_symmetry` died
on the missing key.

The group results are checked against invariants rather than against a second
implementation: the orbit-stabilizer theorem, Lagrange, and that orbits
partition. A bug in the closure, the stabilizer or the orbit breaks one of them,
and none of the three needs the right answer known in advance.

Run as a whole against the unfixed source, 13 of these 42 fail and the rest pass
either way. The ones that pass are not offered as evidence of the fix; they are
kept as regression guards. The reason they cannot discriminate is itself the
reason the defect survived: `find_apg_automorphisms` returns a group whose
`generators` attribute holds *every element*, so a test routed through it is
taking the full-group path under a generating-set name. A group does generate
itself, so this is correct and not a defect -- but it means the repo's own tests
never exercised the case that was broken. The tests that do discriminate build a
genuine two-element generating set with `symmetric_on_leaves`, or use a single
5-cycle.
"""

from __future__ import annotations

import itertools
import math

import pytest

from grounded_hyperset_theory import AccessiblePointedGraph, Node
from grounded_hyperset_theory.hyper_calculus import (
    Permutation,
    PermutationGroup,
    all_orbits,
    automorphism_group,
    find_apg_automorphisms,
    orbit,
    quotient_by_symmetry,
)


def star(k: int) -> AccessiblePointedGraph:
    """A root with k leaves. Its pointed automorphism group is S_k on the leaves."""
    return AccessiblePointedGraph(
        root=0,
        edges={0: list(range(1, k + 1)), **{i: [] for i in range(1, k + 1)}},
    )


def directed_cycle(n: int) -> AccessiblePointedGraph:
    """A directed n-cycle. Fixing the root leaves only the identity."""
    return AccessiblePointedGraph(root=0, edges={i: [(i + 1) % n] for i in range(n)})


def rotation(n: int) -> Permutation:
    """The n-cycle (0 1 ... n-1) as a permutation of Node(0) .. Node(n-1)."""
    nodes = [Node(i) for i in range(n)]
    return Permutation({nodes[i]: nodes[(i + 1) % n] for i in range(n)})


def symmetric_on_leaves(k: int) -> PermutationGroup:
    """S_k on the leaves 1..k of star(k), from two generators, with the root fixed.

    A transposition and a k-cycle generate the full symmetric group, so this is
    the same group `find_apg_automorphisms(star(k), pointed=True)` returns -- but
    from an actual generating set of size 2 rather than from all k! elements.
    That distinction is the whole subject of this file, so the invariant tests
    that go through `generators` use this and not the automorphism search.
    """
    leaves = [Node(i) for i in range(1, k + 1)]
    root = {Node(0): Node(0)}
    swap = Permutation({**root, **{leaves[0]: leaves[1], leaves[1]: leaves[0]},
                        **{leaf: leaf for leaf in leaves[2:]}})
    cycle = Permutation({**root, **{leaves[i]: leaves[(i + 1) % k] for i in range(k)}})
    return PermutationGroup([swap] if k == 2 else [swap, cycle])


# ============================================================================
# 1. A generating set gives the same orbit as the whole group
# ============================================================================


def test_the_orbit_under_a_single_generator_is_the_whole_cycle() -> None:
    # The central case. One generator, five nodes, and applying it once reaches
    # exactly one of them.
    group = PermutationGroup([rotation(5)])
    assert group.order == 5
    assert len(group.generators) == 1
    assert orbit(Node(0), group.generators) == {Node(i) for i in range(5)}


def test_generators_and_elements_give_the_same_orbit() -> None:
    group = PermutationGroup([rotation(5)])
    for node in group.domain:
        assert orbit(node, group.generators) == orbit(node, group.elements())


def test_a_two_generator_group_agrees_with_its_closure() -> None:
    nodes = [Node(i) for i in range(5)]
    swap = Permutation({nodes[0]: nodes[1], nodes[1]: nodes[0],
                        nodes[2]: nodes[2], nodes[3]: nodes[3], nodes[4]: nodes[4]})
    group = PermutationGroup([rotation(5), swap])
    assert group.order == 120, "the 5-cycle and a transposition generate S_5"
    for node in group.domain:
        assert orbit(node, group.generators) == orbit(node, group.elements())
        assert orbit(node, group.generators) == set(nodes)


def test_a_point_is_in_its_own_orbit() -> None:
    group = PermutationGroup([rotation(4)])
    for node in group.domain:
        assert node in orbit(node, group.generators)


def test_negative_control_applying_each_generator_once_is_not_the_orbit() -> None:
    # The replaced body. Kept so the gap stays legible.
    group = PermutationGroup([rotation(5)])
    one_step = {g.apply(Node(0)) for g in group.generators}
    assert one_step == {Node(1)}, "one application of the single generator"
    assert one_step != orbit(Node(0), group.generators)


# ============================================================================
# 2. all_orbits is a partition
# ============================================================================


@pytest.mark.parametrize("k", [2, 3, 4, 5])
def test_orbits_cover_every_node_and_are_disjoint(k: int) -> None:
    apg = star(k)
    group = find_apg_automorphisms(apg, pointed=True)
    for permutations in (symmetric_on_leaves(k).generators, group.elements()):
        blocks = all_orbits(apg, permutations)
        assert set().union(*blocks) == set(apg.nodes)
        assert all(not (a & b) for a, b in itertools.combinations(blocks, 2))


def test_a_partition_holds_for_a_generating_set_that_misses_nodes_in_one_step() -> None:
    apg = AccessiblePointedGraph(root=0, edges={0: [1, 2, 3, 4], **{i: [] for i in range(1, 5)}})
    group = PermutationGroup([rotation(5)])
    blocks = all_orbits(apg, group.generators)
    assert blocks == [{Node(i) for i in range(5)}]
    assert set().union(*blocks) == set(apg.nodes)


def test_negative_control_one_step_images_left_nodes_unblocked() -> None:
    # The replaced body, reproduced. Two of five nodes ended up in no block, and
    # a quotient over that is not defined.
    apg = AccessiblePointedGraph(root=0, edges={0: [1, 2, 3, 4], **{i: [] for i in range(1, 5)}})
    permutations = list(PermutationGroup([rotation(5)]).generators)
    target = set(apg.nodes)
    visited: set[Node] = set()
    blocks: list[set[Node]] = []
    for n in sorted(target, key=lambda x: str(x.id)):
        if n not in visited:
            block = {g.apply(n) for g in permutations if g.apply(n) in target}
            visited.update(block)
            blocks.append(block)
    assert set().union(*blocks) != target, "the blocks did not cover the graph"


def test_the_star_collapses_its_leaves_into_one_block() -> None:
    apg = star(4)
    group = find_apg_automorphisms(apg, pointed=True)
    blocks = all_orbits(apg, group.elements())
    assert sorted(len(b) for b in blocks) == [1, 4], "the root alone, and the four leaves"


def test_a_directed_cycle_has_only_singleton_orbits_when_pointed() -> None:
    apg = directed_cycle(5)
    group = find_apg_automorphisms(apg, pointed=True)
    assert group.order == 1
    assert all(len(b) == 1 for b in all_orbits(apg, group.elements()))


